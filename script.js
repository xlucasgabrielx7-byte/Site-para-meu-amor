function showToast(text) {
  clearTimeout(toastTimer);
  $('toast').textContent = text;
  $('toast').classList.add('show');
  toastTimer = setTimeout(() => $('toast').classList.remove('show'), 2300);
}

function createHeart(symbol) {
  const heart = document.createElement('span');
  heart.className = 'floating-heart';
  heart.textContent = symbol || ['♥','♡','❤','💜','💗'][Math.floor(Math.random()*5)];
  heart.style.left = `${Math.random()*100}%`;
  heart.style.fontSize = `${12 + Math.random()*19}px`;
  heart.style.animationDuration = `${5 + Math.random()*6}s`;
  $('hearts').appendChild(heart);
  setTimeout(() => heart.remove(), 12000);
}
function burstHearts(amount = 12) { for (let i=0;i<amount;i++) setTimeout(() => createHeart(), i*45); }
function startHearts() { setInterval(() => { if (document.visibilityState === 'visible') createHeart(); }, 720); }

