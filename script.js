const $ = id => document.getElementById(id);
let current = 0;
let answered = false;
let tipVisible = false;
let toastTimer;

function showScreen(id) {
  document.querySelectorAll('.screen').forEach(screen => screen.classList.remove('active'));
  $(id).classList.add('active');
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

function renderQuestion() {
  const q = CONFIG.perguntas[current];
  answered = false;
  tipVisible = false;

  $('questionNumber').textContent = current + 1;
  $('counter').textContent = `${current + 1}/${CONFIG.perguntas.length}`;
  $('progressBar').style.width = `${((current + 1) / CONFIG.perguntas.length) * 100}%`;
  $('question').textContent = q.pergunta;
  $('questionHint').textContent = 'A dica está escondida. Se precisar, toque em 💡 Dica.';
  $('quizPhoto').src = q.foto;
  $('feedback').textContent = '';
  $('feedback').className = 'feedback';
  $('nextBtn').hidden = true;
  updateLikeCount();

  const options = $('options');
  options.innerHTML = '';
  q.opcoes.forEach((text, index) => {
    const button = document.createElement('button');
    button.className = 'option';
    button.type = 'button';
    button.textContent = text;
    button.addEventListener('click', () => checkAnswer(index, button));
    options.appendChild(button);
  });
}

function checkAnswer(index, clicked) {
  if (answered) return;
  const q = CONFIG.perguntas[current];

  if (index === q.correta) {
    answered = true;
    clicked.classList.add('correct');
    document.querySelectorAll('.option').forEach(button => { button.disabled = true; });
    $('feedback').textContent = `✓ ${q.acerto}`;
    $('feedback').className = 'feedback good';
    $('nextBtn').hidden = false;
    burstHearts(18);
  } else {
    clicked.classList.add('wrong');
    $('feedback').textContent = `✕ ${q.erro}`;
    $('feedback').className = 'feedback bad';
    setTimeout(() => clicked.classList.remove('wrong'), 450);
    createHeart('💔');
  }
}

function nextQuestion() {
  if (!answered) return;
  if (current < CONFIG.perguntas.length - 1) {
    current++;
    renderQuestion();
  } else {
    $('finalTitle').textContent = CONFIG.casal.tituloFinal;
    $('finalText').textContent = CONFIG.casal.mensagemFinal;
    $('signature').textContent = CONFIG.casal.assinatura;
    $('finalPhoto').src = CONFIG.casal.final;
    showScreen('final');
    burstHearts(42);
  }
}

function toggleTip() {
  const q = CONFIG.perguntas[current];
  tipVisible = !tipVisible;
  $('questionHint').textContent = tipVisible ? `💡 ${q.dica}` : 'A dica está escondida. Se precisar, toque em 💡 Dica.';
  $('tipBtn').textContent = tipVisible ? '💡 Esconder' : '💡 Dica';
}

function likeKey() { return `romantico-liked-${current}`; }
function updateLikeCount() {
  const liked = localStorage.getItem(likeKey()) === '1';
  $('likeBtn').classList.toggle('liked', liked);
  $('likeBtn').querySelector('span').textContent = liked ? '1' : '0';
  $('likeBtn').firstChild.textContent = liked ? '♥ ' : '♡ ';
}
function toggleLike() {
  const liked = localStorage.getItem(likeKey()) === '1';
  if (liked) localStorage.removeItem(likeKey());
  else localStorage.setItem(likeKey(), '1');
  updateLikeCount();
  showToast(liked ? 'Curtida removida ❤️' : 'Você curtiu essa lembrança! ❤️');
  if (!liked) burstHearts(8);
}

function openModal(content) {
  $('modalContent').innerHTML = content;
  $('modal').classList.add('open');
  $('modal').setAttribute('aria-hidden', 'false');
}
function closeModal() {
  $('modal').classList.remove('open');
  $('modal').setAttribute('aria-hidden', 'true');
}

